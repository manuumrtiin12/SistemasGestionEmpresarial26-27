
categorias = [
    "Hardware",
    "Software",
    "Hardware",
    "Servicios",
    "Software"
]

conjunto = set(categorias)
print(conjunto)

# ¿Qué ha ocurrido con los elementos repetidos?
# Un conjunto (set) no admite elementos duplicados, así que "Hardware" y 
# "Software" aparecen una sola vez. Además, los conjuntos no mantienen
# un orden concreto.
